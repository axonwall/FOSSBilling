// FOSSBilling Phase 5 R5j: generate src/server/install-schema.ts from the
// PHP capture corpus (docs/nextjs-strangler/phase5/captures46/).
//
// The TS installer does NOT hand-maintain 63 tables of DDL: this script
// parses Doctrine's own per-platform DDL (php-platform-ddl.json) and the
// live SQLite structure (php-fresh-schema.json), cross-verifies every
// fact across both sources (failing loudly on ANY disagreement), and
// emits structured TS table definitions. The DDL emitters in
// src/server/install-schema-ddl.ts then reproduce Doctrine's statements
// from those definitions; the installer-test proves the reproduction
// byte-for-byte against the same captures, and proves the live installed
// schema against the live PHP dump.
//
// Usage: node scripts/generate-install-schema.mjs [captures-dir] [out-file]
// Defaults: ../docs/nextjs-strangler/phase5/captures46,
//           src/server/install-schema.ts (relative to apps/nextjs).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const APP = path.resolve(HERE, "..");
const capturesDir = process.argv[2] ?? path.resolve(APP, "..", "..", "docs", "nextjs-strangler", "phase5", "captures46");
const outFile = process.argv[3] ?? path.join(APP, "src", "server", "install-schema.ts");

function fail(msg) { throw new Error(`generate-install-schema: ${msg}`); }

// Split on top-level commas (depth-0 parens, single/double quotes).
function splitTopLevel(s) {
  const parts = [];
  let depth = 0, quote = null, cur = "";
  for (let i = 0; i < s.length; i++) {
    const ch = s[i];
    if (quote) {
      cur += ch;
      if (ch === quote) {
        if (s[i + 1] === quote) { cur += s[i + 1]; i++; } else quote = null;
      }
    } else if (ch === "'" || ch === '"') { quote = ch; cur += ch; }
    else if (ch === "(") { depth++; cur += ch; }
    else if (ch === ")") { depth--; cur += ch; }
    else if (ch === "," && depth === 0) { parts.push(cur.trim()); cur = ""; }
    else cur += ch;
  }
  if (cur.trim()) parts.push(cur.trim());
  return parts;
}

// Parse one identifier: "quoted" or bare.
function parseIdent(s) {
  const m = /^"([^"]+)"(.*)$/.exec(s) ?? /^([A-Za-z_][A-Za-z0-9_]*)(.*)$/.exec(s);
  if (!m) fail(`cannot parse identifier from ${JSON.stringify(s)}`);
  return { name: m[1], quoted: s.startsWith('"'), rest: m[2].trim() };
}

// Parse a column definition (sqlite or pg CREATE part, after the name).
function parseColumn(part, platform) {
  const id = parseIdent(part);
  let rest = id.rest;
  const typeMatch = /^([A-Za-z]+(?:\s*\([^)]*\))?(?:\s+WITH(?:OUT)? TIME ZONE)?)(.*)$/.exec(rest);
  if (!typeMatch) fail(`cannot parse type from ${JSON.stringify(part)}`);
  const rawType = typeMatch[1].replace(/\s+/g, "");
  rest = typeMatch[2].trim();
  let autoinc = false, pk = false, notNull = false, def = null;
  if (/^PRIMARY KEY AUTOINCREMENT\b/.test(rest)) { pk = true; autoinc = true; rest = rest.replace(/^PRIMARY KEY AUTOINCREMENT\b/, "").trim(); }
  else if (/^PRIMARY KEY\b/.test(rest)) { pk = true; rest = rest.replace(/^PRIMARY KEY\b/, "").trim(); }
  // Postgres renders autoincrement as GENERATED BY DEFAULT AS IDENTITY
  // (the PK itself is a table-level clause there, not inline).
  if (/^GENERATED BY DEFAULT AS IDENTITY\b/.test(rest)) { autoinc = true; rest = rest.replace(/^GENERATED BY DEFAULT AS IDENTITY\b/, "").trim(); }
  if (/^DEFAULT\b/.test(rest)) {
    rest = rest.replace(/^DEFAULT\b/, "").trim();
    if (rest.startsWith("'")) {
      let j = 1, lit = "'";
      while (j < rest.length) {
        lit += rest[j];
        if (rest[j] === "'") { if (rest[j + 1] === "'") { lit += "'"; j += 2; continue; } break; }
        j++;
      }
      def = lit; rest = rest.slice(j + 1).trim();
    } else {
      const m = /^(\S+)(.*)$/.exec(rest);
      def = m[1]; rest = m[2].trim();
    }
  }
  if (/^NOT NULL\b/.test(rest)) { notNull = true; rest = rest.replace(/^NOT NULL\b/, "").trim(); }
  if (rest !== "") fail(`unparsed column tail ${JSON.stringify(rest)} in ${JSON.stringify(part)} (${platform})`);
  return { name: id.name, quoted: id.quoted, rawType, pk, autoinc, notNull, defaultLit: def };
}

function parseCreate(createSql) {
  const m = /^CREATE TABLE\s+("[^"]+"|[A-Za-z_][A-Za-z0-9_]*)\s*\((.*)\)\s*$/.exec(createSql);
  if (!m) fail(`cannot parse CREATE TABLE: ${createSql.slice(0, 120)}`);
  const tableId = parseIdent(m[1]);
  const parts = splitTopLevel(m[2]);
  const columns = [], tablePk = [], fks = [];
  for (const part of parts) {
    if (/^PRIMARY KEY\s*\(/.test(part)) {
      const cols = part.replace(/^PRIMARY KEY\s*\(/, "").replace(/\)$/, "");
      tablePk.push(...splitTopLevel(cols).map((c) => parseIdent(c.trim()).name));
    } else if (/^CONSTRAINT\b/.test(part)) {
      const fm = /^CONSTRAINT\s+(\S+)\s+FOREIGN KEY\s*\(([^)]*)\)\s+REFERENCES\s+("[^"]+"|[A-Za-z_][A-Za-z0-9_]*)\s*\(([^)]*)\)\s*(.*?)\s*$/.exec(part);
      if (!fm) fail(`cannot parse FK: ${part.slice(0, 160)}`);
      const tail = fm[5];
      const onDelete = /ON DELETE CASCADE/.test(tail) ? "CASCADE" : null;
      if (!/^(ON DELETE CASCADE\s+)?NOT DEFERRABLE INITIALLY IMMEDIATE$/.test(tail)) fail(`unexpected FK tail ${JSON.stringify(tail)}`);
      fks.push({ name: fm[1], columns: splitTopLevel(fm[2]).map((c) => c.trim()), refTable: parseIdent(fm[3]).name, refColumns: splitTopLevel(fm[4]).map((c) => c.trim()), onDelete });
    } else {
      columns.push(parseColumn(part, "create"));
    }
  }
  return { table: tableId.name, tableQuoted: tableId.quoted, columns, tablePk, fks };
}

function parseIndex(stmt) {
  const m = /^CREATE\s+(UNIQUE\s+)?INDEX\s+(\S+)\s+ON\s+("[^"]+"|[A-Za-z_][A-Za-z0-9_]*)\s*\(([^)]*)\)\s*$/.exec(stmt);
  if (!m) fail(`cannot parse index: ${stmt.slice(0, 120)}`);
  return { unique: !!m[1], name: m[2], table: parseIdent(m[3]).name, columns: splitTopLevel(m[4]).map((c) => parseIdent(c.trim()).name) };
}

function parseAlter(stmt) {
  const m = /^ALTER TABLE\s+("[^"]+"|[A-Za-z_][A-Za-z0-9_]*)\s+ADD CONSTRAINT\s+(\S+)\s+FOREIGN KEY\s*\(([^)]*)\)\s+REFERENCES\s+("[^"]+"|[A-Za-z_][A-Za-z0-9_]*)\s*\(([^)]*)\)\s*(.*?)\s*$/.exec(stmt);
  if (!m) fail(`cannot parse ALTER: ${stmt.slice(0, 160)}`);
  const tail = m[6];
  const onDelete = /ON DELETE CASCADE/.test(tail) ? "CASCADE" : null;
  if (!/^(ON DELETE CASCADE\s+)?NOT DEFERRABLE$/.test(tail)) fail(`unexpected ALTER tail ${JSON.stringify(tail)}`);
  return { table: parseIdent(m[1]).name, name: m[2], columns: splitTopLevel(m[3]).map((c) => c.trim()), refTable: parseIdent(m[4]).name, refColumns: splitTopLevel(m[5]).map((c) => c.trim()), onDelete };
}

// Doctrine type derivation from a (sqlite, pg) type pair. Fails loudly
// on any pair this mapping does not know, so a future entity change
// that introduces a new Doctrine type breaks the generator, not the install.
function doctrineType(sqliteCol, pgCol) {
  const s = sqliteCol.rawType, p = pgCol.rawType;
  if (sqliteCol.autoinc) {
    if (p === "BIGINT") return { doctrine: "bigint" };
    if (p === "INT") return { doctrine: "integer" };
    fail(`autoinc pair ${s}/${p} for ${sqliteCol.name}`);
  }
  const map = [
    ["BIGINT", "BIGINT", "bigint", {}],
    ["INTEGER", "INT", "integer", {}],
    ["SMALLINT", "SMALLINT", "smallint", {}],
    ["CLOB", "TEXT", "text", {}],
    ["CLOB", "JSON", "json", {}],
    ["BLOB", "BYTEA", "blob", {}],
    ["BOOLEAN", "BOOLEAN", "boolean", {}],
    ["DATETIME", "TIMESTAMP(0)WITHOUTTIMEZONE", "datetime", {}],
    ["DATE", "DATE", "date", {}],
  ];
  for (const [st, pt, d] of map) if (s === st && p === pt) return { doctrine: d };
  const vm = /^VARCHAR\((\d+)\)$/.exec(s);
  if (vm && p === `VARCHAR(${vm[1]})`) return { doctrine: "string", length: Number(vm[1]) };
  const nm = /^NUMERIC\((\d+),(\d+)\)$/.exec(s);
  if (nm && p === `NUMERIC(${nm[1]},${nm[2]})`) return { doctrine: "decimal", precision: Number(nm[1]), scale: Number(nm[2]) };
  fail(`unknown type pair ${s}/${p} for ${sqliteCol.name}`);
}

const ddl = JSON.parse(fs.readFileSync(path.join(capturesDir, "php-platform-ddl.json"), "utf8"));
const live = JSON.parse(fs.readFileSync(path.join(capturesDir, "php-fresh-schema.json"), "utf8"));
const tables = [];

for (const tableName of Object.keys(ddl.tables).sort()) {
  const entry = ddl.tables[tableName];
  const sq = parseCreate(entry.sqlite_ddl[0]);
  const pg = parseCreate(entry.postgres_ddl[0]);
  if (sq.table !== tableName || pg.table !== tableName) fail(`table name mismatch for ${tableName}`);
  if (sq.columns.length !== pg.columns.length) fail(`column count mismatch for ${tableName}`);
  const sqIndexes = entry.sqlite_ddl.slice(1).map(parseIndex);
  const pgIndexes = entry.postgres_ddl.slice(1).filter((s) => s.startsWith("CREATE")).map(parseIndex);
  const pgAlters = entry.postgres_ddl.slice(1).filter((s) => s.startsWith("ALTER")).map(parseAlter);
  if (JSON.stringify(sqIndexes) !== JSON.stringify(pgIndexes)) fail(`index mismatch for ${tableName}`);
  if (JSON.stringify(sq.fks.map(({ name, columns, refTable, refColumns, onDelete }) => ({ name, columns, refTable, refColumns, onDelete }))) !==
      JSON.stringify(pgAlters.map(({ name, columns, refTable, refColumns, onDelete }) => ({ name, columns, refTable, refColumns, onDelete })))) {
    fail(`FK mismatch for ${tableName}`);
  }
  // Live-structure cross-check (PRAGMA vs parsed sqlite CREATE).
  const liveCols = live.tables[tableName].columns;
  if (liveCols.length !== sq.columns.length) fail(`live column count mismatch for ${tableName}`);
  // Postgres puts the PK in a table-level clause; SQLite inlines it
  // (except session, table-level on both). Compare PK sets, not flags.
  const sqPk = new Set([...sq.columns.filter((c) => c.pk).map((c) => c.name), ...sq.tablePk]);
  const pgPk = new Set([...pg.columns.filter((c) => c.pk).map((c) => c.name), ...pg.tablePk]);
  if (sqPk.size !== 1 || pgPk.size !== 1 || [...sqPk][0] !== [...pgPk][0]) {
    fail(`pk set mismatch for ${tableName}: sqlite=${[...sqPk]} pg=${[...pgPk]} (generator assumes single-column PKs)`);
  }
  const pkName = [...sqPk][0];
  const columns = sq.columns.map((sc, i) => {
    const pc = pg.columns[i];
    if (sc.name !== pc.name) fail(`column order mismatch for ${tableName} at ${i}`);
    if (sc.autoinc !== pc.autoinc) fail(`autoinc mismatch for ${tableName}.${sc.name}`);
    if (sc.notNull !== pc.notNull) fail(`notnull mismatch for ${tableName}.${sc.name}`);
    const lc = liveCols[i];
    if (lc.name !== sc.name || lc.type.replace(/\s+/g, "") !== sc.rawType || !!lc.notnull !== sc.notNull || (lc.pk ? 1 : 0) !== (sc.name === pkName ? 1 : 0)) {
      fail(`live mismatch for ${tableName}.${sc.name}: live=${JSON.stringify(lc)} parsed=${JSON.stringify(sc)}`);
    }
    // PRAGMA dflt_value: quoted string for string defaults, 'NULL' for
    // DEFAULT NULL, null when no DEFAULT clause.
    const liveDefault = lc.default === null ? null : lc.default;
    if (liveDefault !== sc.defaultLit) fail(`live default mismatch for ${tableName}.${sc.name}: live=${JSON.stringify(liveDefault)} parsed=${JSON.stringify(sc.defaultLit)}`);
    const dt = doctrineType(sc, pc);
    return {
      name: sc.name, ...dt,
      notNull: sc.notNull,
      defaultSqlite: sc.defaultLit, defaultPg: pc.defaultLit,
      pk: sc.name === pkName, autoinc: sc.autoinc,
      quoteSqlite: sc.quoted, quotePg: pc.quoted,
    };
  });
  tables.push({
    name: tableName, quoteSqlite: sq.tableQuoted, quotePg: pg.tableQuoted,
    columns, primaryKey: sq.tablePk,
    foreignKeys: sq.fks,
    indexes: sqIndexes.map(({ name, unique, columns: cols }) => ({ name, unique, columns: cols })),
  });
}

function tsString(s) { return JSON.stringify(s); }
function colTs(c) {
  const parts = [`name: ${tsString(c.name)}`, `doctrine: ${tsString(c.doctrine)}`];
  if (c.length !== undefined) parts.push(`length: ${c.length}`);
  if (c.precision !== undefined) parts.push(`precision: ${c.precision}`, `scale: ${c.scale}`);
  parts.push(`notNull: ${c.notNull}`);
  parts.push(`defaultSqlite: ${c.defaultSqlite === null ? "null" : tsString(c.defaultSqlite)}`);
  parts.push(`defaultPg: ${c.defaultPg === null ? "null" : tsString(c.defaultPg)}`);
  if (c.pk) parts.push(`pk: true`);
  if (c.autoinc) parts.push(`autoinc: true`);
  if (c.quoteSqlite) parts.push(`quoteSqlite: true`);
  if (c.quotePg) parts.push(`quotePg: true`);
  return `{ ${parts.join(", ")} }`;
}

let out = `// GENERATED by scripts/generate-install-schema.mjs from
// docs/nextjs-strangler/phase5/captures46/php-platform-ddl.json +
// php-fresh-schema.json (Doctrine's own per-platform DDL + the live
// SQLite structure of a real PHP SchemaInstaller run). DO NOT EDIT BY
// HAND: re-run the generator after any entity change, and let the
// installer-test prove the emitters still reproduce Doctrine's DDL
// byte-for-byte. Table order is alphabetical; column/index/FK order is
// Doctrine's emission order, which the emitters must preserve.

export type InstallDoctrineType =
  | "bigint" | "integer" | "smallint" | "string" | "text" | "blob"
  | "boolean" | "datetime" | "date" | "decimal" | "json";

export interface InstallColumn {
  name: string;
  doctrine: InstallDoctrineType;
  length?: number;
  precision?: number;
  scale?: number;
  notNull: boolean;
  /** SQL literal exactly as Doctrine emits it, or null for no DEFAULT clause. */
  defaultSqlite: string | null;
  defaultPg: string | null;
  pk?: boolean;
  autoinc?: boolean;
  quoteSqlite?: boolean;
  quotePg?: boolean;
}

export interface InstallForeignKey {
  name: string;
  columns: string[];
  refTable: string;
  refColumns: string[];
  onDelete: "CASCADE" | null;
}

export interface InstallIndex {
  name: string;
  unique: boolean;
  columns: string[];
}

export interface InstallTable {
  name: string;
  quoteSqlite?: boolean;
  quotePg?: boolean;
  columns: InstallColumn[];
  /** Table-level PRIMARY KEY (only session); empty when the PK is inline. */
  primaryKey: string[];
  foreignKeys: InstallForeignKey[];
  indexes: InstallIndex[];
}

export const INSTALL_SCHEMA: InstallTable[] = [
`;
for (const t of tables) {
  out += `  {\n    name: ${tsString(t.name)}`;
  if (t.quoteSqlite) out += `, quoteSqlite: true`;
  if (t.quotePg) out += `, quotePg: true`;
  out += `,\n    columns: [\n`;
  for (const c of t.columns) out += `      ${colTs(c)},\n`;
  out += `    ],\n    primaryKey: [${t.primaryKey.map(tsString).join(", ")}],\n`;
  out += `    foreignKeys: [${t.foreignKeys.map((f) => `{ name: ${tsString(f.name)}, columns: [${f.columns.map(tsString).join(", ")}], refTable: ${tsString(f.refTable)}, refColumns: [${f.refColumns.map(tsString).join(", ")}], onDelete: ${f.onDelete === null ? "null" : tsString(f.onDelete)} }`).join(", ")}],\n`;
  out += `    indexes: [${t.indexes.map((ix) => `{ name: ${tsString(ix.name)}, unique: ${ix.unique}, columns: [${ix.columns.map(tsString).join(", ")}] }`).join(", ")}],\n  },\n`;
}
out += `];\n\nexport const INSTALL_SCHEMA_TABLE_COUNT = ${tables.length};\n`;
fs.writeFileSync(outFile, out);
console.log(`wrote ${outFile}: ${tables.length} tables, ${tables.reduce((n, t) => n + t.columns.length, 0)} columns`);
