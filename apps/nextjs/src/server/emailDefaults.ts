// File-backed email template defaults, mirroring PHP's Email service
// (Service.php: _getDefaults, getDefaultTemplate, syncBuiltinTemplate,
// resetBuiltinTemplate, createBuiltinTemplateRecord, getVars).
// Defaults live in the PHP tree at modules/<Module>/templates/email/
// <code>.html.twig; the tree is FOSSBILLING_PHP_SRC, or the fork's
// own src/ when the Next app runs from apps/nextjs.

import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { decryptV2 } from "./crypt";
import { findDefaultCurrency, getDb, getDbWrite, nowTimestamp } from "./db";

export interface TemplateRowFull {
  id: number; action_code: string; category: string | null; enabled: number;
  subject: string | null; content: string | null; description: string | null;
  vars: string | null; is_custom: number; is_overridden: number;
  last_error: string | null; error_checked_at: string | null;
}

export interface DefaultTemplate {
  action_code: string; category: string; subject: string; content: string;
  description: string | null; enabled: number;
}

const CORE_MODULES = new Set([
  "api", "activity", "antispam", "cart", "client", "cron", "currency", "email",
  "extension", "index", "invoice", "order", "page", "product", "profile",
  "security", "servicecustom", "servicedomain", "servicedownloadable",
  "servicehosting", "servicelicense", "staff", "stats", "support", "system",
  "theme", "orderbutton", "formbuilder", "widgets",
]);

export function phpModulesDir(): string {
  const base = process.env.FOSSBILLING_PHP_SRC ?? join(process.cwd(), "..", "..", "src");
  return join(base, "modules");
}

function codeModuleSegment(code: string): string | null {
  const m = /^mod_([a-zA-Z0-9]+)_([a-zA-Z0-9]+)/i.exec(code);
  return m ? m[1].toLowerCase() : null;
}

function ucwordsCode(code: string): string {
  return code.replace(/_/g, " ").split(" ").map((w) => (w ? w[0].toUpperCase() + w.slice(1) : w)).join(" ");
}

/** PHP's auto-generated fallback template body (_getVarsString). */
export function varsStringFallback(): string {
  return [
    "{% apply markdown_to_html %}",
    "",
    "This email template was automatically generated by FOSSBilling extension.   ",
    "Template is ready to be modified.   ",
    "Email templates support a limited sandboxed Twig environment.   ",
    "Use variables passed to the template together with the available globals such as **guest.system_company**, **guest.system_email**, and **FOSSBillingVersion**.",
    "",
    "Example values available in email templates:",
    "",
    "{{ FOSSBillingVersion }}",
    "",
    "{{ guest.system_company.name }}",
    "",
    "{{ guest.system_email.signature }}",
    "",
    "{{ now|date('Y-m-d') }}",
    "",
    "{% endapply %}",
  ].join("\n");
}

function parseDefaultFile(code: string): { subject: string | null; content: string | null } | null {
  const segment = codeModuleSegment(code);
  if (!segment) return null;
  const dir = segment[0].toUpperCase() + segment.slice(1);
  const path = join(phpModulesDir(), dir, "templates", "email", `${code}.html.twig`);
  if (!existsSync(path)) return null;
  const text = readFileSync(path, "utf-8");
  const subject = /\{%-?\s*block subject\s*-?%\}([^\n]*?)\{%-?\s*endblock\s*-?%\}/.exec(text)?.[1] ?? null;
  const content = /\{%-?\s*block content\s*-?%\}((?:.*\n)+?)\{%-?\s*endblock\s*-?%\}/.exec(text)?.[1] ?? null;
  return { subject, content };
}

/** PHP _getDefaults: file blocks win, else the caller's defaults. */
function computeDefaults(code: string, data: Record<string, unknown>): DefaultTemplate {
  const segment = codeModuleSegment(code);
  const file = parseDefaultFile(code);
  const subject = file?.subject
    ?? (typeof data.default_subject === "string" ? data.default_subject : null)
    ?? ucwordsCode(code);
  const content = file?.content
    ?? (typeof data.default_template === "string" ? data.default_template : null)
    ?? varsStringFallback();
  return {
    action_code: code,
    category: segment ?? "custom",
    subject,
    content,
    description: typeof data.default_description === "string" ? data.default_description : null,
    enabled: file?.content ? 1 : 0,
  };
}

/** Null when the code has no file-backed default (getDefaultTemplate). */
export function getDefaultTemplate(code: string, data: Record<string, unknown> = {}): DefaultTemplate | null {
  if (!parseDefaultFile(code)) return null;
  return computeDefaults(code, data);
}

export function hasDefaultTemplate(code: string): boolean {
  return parseDefaultFile(code) !== null;
}

/** Effective subject/content (getEffectiveTemplateParts). */
export function effectiveParts(row: TemplateRowFull): [string, string] {
  if (row.is_custom) return [row.subject ?? "", row.content ?? ""];
  if (row.subject !== null && row.content !== null) return [row.subject, row.content];
  const def = getDefaultTemplate(row.action_code);
  if (def) return [row.subject ?? def.subject, row.content ?? def.content];
  return [row.subject ?? "", row.content ?? ""];
}

/** Fields syncBuiltinTemplate would change (empty = no change). */
export function syncBuiltinChanges(row: TemplateRowFull, def: DefaultTemplate): Partial<TemplateRowFull> {
  const out: Partial<TemplateRowFull> = {};
  if ((row.category === null || row.category === "") && def.category) out.category = def.category;
  if ((row.description === null || row.description === "") && def.description) out.description = def.description;
  if (!row.is_overridden) {
    if (row.subject !== def.subject) out.subject = def.subject;
    if (row.content !== def.content) out.content = def.content;
  }
  return out;
}

export async function applyRowChanges(id: number, changes: Partial<TemplateRowFull>): Promise<void> {
  const keys = Object.keys(changes) as (keyof TemplateRowFull)[];
  if (!keys.length) return;
  const sets = keys.map((k) => `${k} = ?`).join(", ");
  const vals = keys.map((k) => {
    const v = changes[k] as unknown;
    return v === null || v === undefined ? null : (v as string | number);
  });
  await getDbWrite().prepare(`UPDATE email_template SET ${sets} WHERE id = ?`).run(...vals, id);
}

/** Create a built-in record; staff-category templates get all groups. */
export async function createBuiltinRecord(code: string, def: DefaultTemplate): Promise<number> {
  const info = await getDbWrite().insertAndGetId(`INSERT INTO email_template (action_code, category, enabled, is_custom, is_overridden, subject, content, description, vars, last_error)
     VALUES (?, ?, ?, 0, 0, ?, ?, ?, NULL, NULL)`, code, def.category, def.enabled, def.subject, def.content, def.description);
  const id = Number(info);
  if (def.category === "staff") {
    const groups = await getDb().prepare("SELECT id FROM admin_group ORDER BY id ASC").all() as unknown as { id: number }[];
    const now = nowTimestamp();
    for (const g of groups) {
      await getDbWrite().prepare(
        "INSERT INTO email_template_group (admin_group_id, created_at, email_template_id) VALUES (?, ?, ?)"
      ).run(g.id, now, id);
    }
  }
  return id;
}

/**
 * getOrCreateTemplateByCode: existing row (synced when built-in), else a
 * built-in record when a file default exists, else a custom record from
 * the caller's defaults. Returns the row id.
 */
export async function getOrCreateTemplateId(code: string, data: Record<string, unknown>): Promise<number> {
  const existing = await getDb().prepare("SELECT * FROM email_template WHERE action_code = ?").get(code) as unknown as TemplateRowFull | undefined;
  if (existing) {
    if (!existing.is_custom) {
      const def = getDefaultTemplate(code, data);
      if (def) await applyRowChanges(existing.id, syncBuiltinChanges(existing, def));
    }
    return existing.id;
  }
  const def = getDefaultTemplate(code, data);
  if (def) return await createBuiltinRecord(code, def);
  // No file default: a custom record from the caller's defaults, always
  // disabled (PHP _getDefaults leaves enabled=0 without a content block).
  const fallback = computeDefaults(code, data);
  const info = await getDbWrite().insertAndGetId(`INSERT INTO email_template (action_code, category, enabled, is_custom, is_overridden, subject, content, description)
     VALUES (?, ?, 0, 1, 0, ?, ?, ?)`, code, fallback.category, fallback.subject, fallback.content, fallback.description);
  return Number(info);
}

function deepMerge(base: Record<string, unknown>, over: Record<string, unknown>): Record<string, unknown> {
  const out: Record<string, unknown> = { ...base };
  for (const [k, v] of Object.entries(over)) {
    if (v && typeof v === "object" && !Array.isArray(v)
      && out[k] && typeof out[k] === "object" && !Array.isArray(out[k])) {
      out[k] = deepMerge(out[k] as Record<string, unknown>, v as Record<string, unknown>);
    } else {
      out[k] = v;
    }
  }
  return out;
}

/** Stored vars (decrypted) with PHP's getVars defaults merged underneath. */
export async function templateVars(row: TemplateRowFull): Promise<Record<string, unknown>> {
  let stored: Record<string, unknown> = {};
  if (row.vars) {
    const plain = decryptV2(row.vars);
    if (plain) {
      try {
        const parsed = JSON.parse(plain) as unknown;
        if (parsed && typeof parsed === "object" && !Array.isArray(parsed)) stored = parsed as Record<string, unknown>;
      } catch { /* undecryptable/unparseable -> [] like PHP */ }
    }
  }
  const code = row.action_code;
  if (code.startsWith("mod_invoice_")) {
    const invoice = (stored.invoice && typeof stored.invoice === "object" && !Array.isArray(stored.invoice))
      ? { ...(stored.invoice as Record<string, unknown>) } : {};
    if (invoice.total === undefined || invoice.total === null) invoice.total = 0;
    if (!invoice.currency) invoice.currency = (await findDefaultCurrency())?.code ?? "USD";
    stored = { ...stored, invoice };
  }
  const staff = { id: 1, email: "staff@example.com", name: "Staff Member", signature: "" };
  const client = {
    id: 1, email: "client@example.com", email_approved: true, type: "individual",
    company: "", company_vat: "", company_number: "", first_name: "Example", last_name: "Client",
    gender: "", birthday: "", phone_cc: "", phone: "", address_1: "", address_2: "",
    city: "", state: "", postcode: "", country: "", currency: "", lang: "", timezone: "",
  };
  const message = {
    id: 1, content: "Example ticket message", attachment: "", created_at: "", updated_at: "",
    author: { name: "Example Client", role: "client" },
  };
  const ticket = {
    id: 1, subject: "Example support ticket", status: "open", priority: 100,
    created_at: "", updated_at: "", replies: 0, first: message,
    helpdesk: { id: 1, name: "Support", can_reopen: true },
    author: { id: 1, first_name: "Example", last_name: "Client", email: "client@example.com", role: "client" },
    client: { id: 1, first_name: "Example", last_name: "Client" },
    messages: [message],
  };
  const staffTicket = { ...ticket, client };
  let defaults: Record<string, unknown> = {};
  if (["mod_support_ticket_staff_open", "mod_support_ticket_staff_close", "mod_support_ticket_staff_reply"].includes(code)) {
    defaults = { c: client, ticket };
  } else if (["mod_staff_ticket_open", "mod_staff_ticket_reply", "mod_staff_ticket_close"].includes(code)) {
    defaults = { staff, ticket: staffTicket };
  } else if (code === "mod_staff_password_reset_approve") {
    defaults = { c: staff };
  } else if (code === "mod_staff_client_signup") {
    defaults = { c: client, staff };
  }
  return deepMerge(defaults, stored);
}

export async function isModuleActive(moduleLower: string): Promise<boolean> {
  if (CORE_MODULES.has(moduleLower)) return true;
  const row = await getDb().prepare("SELECT status FROM extension WHERE type = 'mod' AND name = ?").get(moduleLower) as unknown as { status: string } | undefined;
  return row?.status === "installed";
}

/** All file-backed template codes in the PHP tree, sorted by code. */
export function listDefaultTemplateCodes(): { code: string; module: string }[] {
  const out: { code: string; module: string }[] = [];
  const modsDir = phpModulesDir();
  let mods: string[] = [];
  try { mods = readdirSync(modsDir, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name); } catch { return out; }
  for (const mod of mods) {
    const dir = join(modsDir, mod, "templates", "email");
    let files: string[] = [];
    try { files = readdirSync(dir).filter((f) => f.endsWith(".html.twig")); } catch { continue; }
    for (const f of files) out.push({ code: f.slice(0, -".html.twig".length), module: mod.toLowerCase() });
  }
  return out.sort((a, b) => (a.code < b.code ? -1 : a.code > b.code ? 1 : 0));
}
