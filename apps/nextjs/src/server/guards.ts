export async function enforceAdminGuards(ctx: CallContext, role: string, module: string, method: string) {
  const guards = ADMIN_GUARDS[`${role}/${module}/${method}`];
  if (!guards) return;
  for (const [mod, key] of guards) await requirePermission(ctx, mod, key);
}

/**
 * Core modules, from FOSSBilling\\Module::CORE_MODULES. The dispatcher
 * activation gate (715) passes core modules unconditionally; any other
 * module must have an installed extension row.
 */
const CORE_MODULES = new Set([
  "api", "activity", "antispam", "cart", "client", "cron", "currency", "email", "extension",
  "index", "invoice", "order", "page", "product", "profile", "security", "servicecustom",
  "servicedomain", "servicedownloadable", "servicehosting", "servicelicense", "staff", "stats",
  "support", "system", "theme", "orderbutton", "formbuilder", "widgets",
]);

async function isModuleActive(module: string): Promise<boolean> {
  if (CORE_MODULES.has(module)) return true;
  const row = await getDb()
    .prepare("SELECT 1 AS x FROM extension WHERE type = ? AND name = ? AND status = ? LIMIT 1")
    .get("mod", module, "installed") as { x: number } | undefined;
  return !!row;
}

/**
 * Dispatcher-level gates (Api\\Dispatcher::dispatchWithArguments),
 * consulted by the seam route after CSRF and before the handler, in
 * PHP's order:
 *  1. Identity (201) — the API controller authenticates before the
 *     dispatcher runs, so an unauthenticated caller gets 201 even for
 *     a non-installed module.
 *  2. Activation (715) — every role: `FOSSBilling module <mod> is
 *     not installed/activated` for non-core, non-installed modules.
 *  3. Admin module access (725) — admin role only:
 *     `You do not have access to the <mod> module` when
 *     hasPermission(identity, module) is false. This fires before the
 *     method body, so it also gates is_allowed and get_navigation
 *     themselves, and every unguarded endpoint.
 *  4. Method guards (403) — the ADMIN_GUARDS table above.
 * The update-finalization bypass (a pending update lets certain admin
 * calls skip gate 3) is not modeled: the reference install has no
 * update finalization pending.
 * Precedence note, as with the method guards: PHP validates
 * RequiredParams between gates 3 and 4, so a call that is BOTH
 * param-invalid AND method-denied gets the param error from PHP but
 * the 403 from TS. Only that combined case differs.
 */
export async function enforceDispatcherGates(ctx: CallContext, role: string, module: string, method: string) {
  if (role === "admin" && !ctx.session?.admin) throw new FbError("Authentication Failed", 201);
  if (role === "client" && !ctx.session?.client) throw new FbError("Authentication Failed", 201);
  if (!await isModuleActive(module)) {
    throw new FbError(`FOSSBilling module ${module} is not installed/activated`, 715);
  }
  if (role === "admin") {
    const adminId = ctx.session!.admin!.id;
    if (!await hasPermission(adminId, module)) {
      throw new FbError(`You do not have access to the ${module} module`, 725);
    }
  }
  await enforceAdminGuards(ctx, role, module, method);
}
