// FOSSBilling Phase 5 R5j: config.php generation for the TS installer.
// Mirrors src/install/install.php's getConfigOutput exactly: start from
// the config-sample.php defaults (transcribed verbatim — the TS subset
// parser cannot evaluate the sample, which contains getenv() calls,
// __DIR__ concatenations and bin2hex(random_bytes(16))), then overwrite
// exactly the keys getConfigOutput overwrites. The installer-test proves
// the key set equals sample + overrides and the deterministic values
// match, so a transcription drift breaks the test, not an install.
//
// Fresh secrets (salt, instance_id) are inputs, generated by the caller
// with a cryptographic RNG — this module never generates or logs them.
import * as fs from "node:fs";
import { serializeConfig, type PhpConfig } from "./config-store";

export const INSTALL_VERSION = "0.0.1";

/** PHP Version::isPreviewVersion: preview = (version === '0.0.1' OR not valid semver). */
export function isPreviewVersion(version: string): boolean {
  if (version === "0.0.1") return true;
  return !/^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(?:-((?:0|[1-9]\d*|\d*[a-zA-Z-][0-9a-zA-Z-]*)(?:\.(?:0|[1-9]\d*|\d*[a-zA-Z-][0-9a-zA-Z-]*))*))?(?:\+([0-9a-zA-Z-]+(?:\.[0-9a-zA-Z-]+)*))?$/.test(
    version,
  );
}

/** PHP Tools::normalizePort: int/string -> trim -> int in 1..65535, else the default. */
export function normalizePort(value: unknown, defaultPort: number | null): number | null {
  const s = String(value ?? "").trim();
  if (!/^-?\d+$/.test(s)) return defaultPort;
  const n = Number(s);
  if (!Number.isInteger(n) || n < 1 || n > 65535) return defaultPort;
  return n;
}

/**
 * PHP install.php normalizeSystemUrl: trim, prepend https:// when no
 * scheme, require http/https with a host, and normalize to lowercase
 * scheme + host + optional port + '/' + trimmed path, trailing slash.
 * Throws with PHP's exact messages on invalid input.
 */
export function normalizeSystemUrl(raw: string): string {
  const trimmed = raw.trim();
  if (trimmed === "") throw new Error("The FOSSBilling URL is required.");
  // PHP: prepend https:// when the string contains no '://' anywhere.
  const withScheme = trimmed.includes("://") ? trimmed : `https://${trimmed}`;
  // Mirror parse_url's decomposition: optional userinfo (dropped),
  // host verbatim (PHP lowercases ONLY the scheme), optional numeric
  // port, path with any query/fragment dropped.
  const m = /^(https?):\/\/(?:[^@/:]+@)?(\[[^\]]+\]|[^/:]+)(?::(\d+))?(?=[/?#]|$)([^?#]*)?(?:[?#].*)?$/i.exec(withScheme);
  if (!m) throw new Error("The FOSSBilling URL must be a valid HTTP or HTTPS URL.");
  const scheme = m[1]!.toLowerCase();
  const host = m[2]!;
  const port = m[3];
  const rawPath = m[4] ?? "";
  const pathPart = rawPath.replace(/^\/+|\/+$/g, "");
  const base = `${scheme}://${host}${port !== undefined ? `:${port}` : ""}`;
  const joined = `${base}/${pathPart}`;
  return joined.replace(/\/+$/, "") + "/";
}

/** The normalized URL with its scheme stripped (getConfigOutput's `url`). */
export function stripUrlScheme(normalizedUrl: string): string {
  return normalizedUrl.replace(/^https?:\/\//, "");
}

