export interface InstallConfigInputs {
  systemUrl: string;
  dbDriver: "pdo_sqlite" | "pdo_pgsql";
  dbPath?: string;
  dbHost?: string;
  dbPort?: string;
  dbName?: string;
  dbUser?: string;
  dbPassword?: string;
  reportErrors: boolean;
  locale: string;
  autoDetectLocale: boolean;
  trustedProxies: string[];
  trustedProxyHeaders: string;
  installRoot: string;
  salt: string;
  instanceId: string;
}

/**
 * getConfigOutput, exactly: sample defaults + the installer overrides.
 * Throws with PHP's exact messages for invalid DB port / missing SQLite
 * path. The caller owns the guards (existing config, non-empty DB) and
 * the actual file write.
 */
export function buildInstallConfig(inputs: InstallConfigInputs): { config: PhpConfig; normalizedUrl: string } {
  const normalizedUrl = normalizeSystemUrl(inputs.systemUrl);
  const config = sampleConfigDefaults();
  const security = config["security"] as Record<string, unknown>;
  security["force_https"] = normalizedUrl.startsWith("https://");
  if (inputs.trustedProxies.length > 0) {
    security["trusted_proxies"] = {
      enabled: true,
      proxies: inputs.trustedProxies,
      headers: inputs.trustedProxyHeaders,
    };
  }
  const monitoring = config["debug_and_monitoring"] as Record<string, unknown>;
  monitoring["report_errors"] = inputs.reportErrors;
  monitoring["debug"] = false;
  const preview = isPreviewVersion(INSTALL_VERSION);
  config["update_branch"] = preview ? "preview" : "release";
  const info = config["info"] as Record<string, unknown>;
  info["salt"] = inputs.salt;
  info["instance_id"] = inputs.instanceId;
  config["url"] = stripUrlScheme(normalizedUrl);
  config["path_data"] = `${inputs.installRoot}/data`;
  if (inputs.dbDriver === "pdo_sqlite") {
    if (!inputs.dbPath) throw new Error("The SQLite database file path is required.");
    config["db"] = { driver: "pdo_sqlite", path: inputs.dbPath };
  } else {
    // PHP validates with normalizePort(port) and NO default (invalid ->
    // throw), then writes normalizePort(port, 5432). An absent port
    // defaults to 5432; an explicitly invalid port throws.
    const port = inputs.dbPort === undefined ? 5432 : normalizePort(inputs.dbPort, null);
    if (port === null) throw new Error("Database port is invalid.");
    config["db"] = {
      driver: "pdo_pgsql",
      host: inputs.dbHost ?? "127.0.0.1",
      port,
      name: inputs.dbName ?? "fossbilling",
      user: inputs.dbUser ?? "fossbilling",
      password: inputs.dbPassword ?? "",
    };
  }
  const twig = config["twig"] as Record<string, unknown>;
  twig["cache"] = `${inputs.installRoot}/data/cache`;
  // disable_auto_cron = !preview && !dev. The installer is never a dev
  // runtime (dev = false), and at 0.0.1 preview is true, so fresh
  // installs always get false.
  config["disable_auto_cron"] = !preview;
  const i18n = config["i18n"] as Record<string, unknown>;
  i18n["locale"] = inputs.locale;
  i18n["auto_detect_locale"] = inputs.autoDetectLocale;
  return { config, normalizedUrl };
}

/**
 * Write the INITIAL config file. R5a's writeConfigFile cannot be used
 * here: it backs the prior file up first and THROWS when no prior file
 * exists — which is exactly the fresh-install state. So the installer
 * writes via the same proven serializeConfig output, temp file + rename,
 * with no backup (there is nothing to back up). All later updates go
 * through writeConfigFile.
 */
export function writeInitialConfig(config: PhpConfig, configPath: string): void {
  const tmp = `${configPath}.tmp-r5j`;
  fs.writeFileSync(tmp, serializeConfig(config), "utf8");
  fs.renameSync(tmp, configPath);
}
