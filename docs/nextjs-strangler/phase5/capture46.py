#!/usr/bin/env python3
"""R5j capture corpus: PHP installer behavior OBSERVED, not assumed.

Regenerates, from PHP's own code, the reference artifacts the TS
installer (scripts/install.ts) and its test (scripts/installer-test.mjs,
parity43.py) compare against:

  captures46/php-fresh-schema.json
      Live SQLite schema + row counts from a real SchemaInstaller +
      InstallSeeder run (disposable SQLite file, repo content.sql).
      Proves the fresh-state rule: 83 content rows + 2 seedAdmin rows
      + 1 nudge row = 86, and enumerates all 63 installer-created tables.
  captures46/php-platform-ddl.json
      Per-table CREATE TABLE / CREATE INDEX / ALTER TABLE ... ADD
      CONSTRAINT SQL as Doctrine's DBAL renders it for the SQLite and
      PostgreSQL platforms, from the SAME filtered metadata
      SchemaInstaller uses (SchemaTool::getSchemaFromMetadata). No live
      Postgres is needed: the Schema object is platform-independent.
  captures46/php-config-sample.json
      config-sample.php EVALUATED by the static PHP binary (salt value
      redacted to its shape; path_data/twig.cache are location-dependent
      and recorded as such). The installer-test compares the TS-written
      config against sample + php-install-overrides, never byte-for-byte
      against PHP's var_export output (different writer, same values).
  captures46/php-install-overrides.json
      The getConfigOutput overrides from src/install/install.php,
      transcribed from source (code-derived, not executed: install.php
      is a web endpoint and cannot run headless without a session).
  captures46/php-finalization-reference.json
      The reference update-finalization.json state file, verbatim (no
      secrets in it). Read-only: this script NEVER mutates it.

Method notes (also in findings-r5j.md):
  * The PHP helpers are embedded below and written to a temp dir at run
    time, so no environment-specific path is committed. They boot with
    the RUNTIME tree's vendor + src, which diff-verified identical to
    the repo tree for every schema-relevant file (Doctrine/, modules/,
    Version, InstallSeeder); content.sql comes from the REPO because
    the runtime's install/ dir was removed post-install.
  * The admin password hash is NEVER emitted: the dump records only its
    presence, prefix ($2y$) and length (60).
  * Exit non-zero if the fresh state is not exactly 86 rows or the table
    count is not 63: the capture must fail loudly rather than bless
    drift.

Usage: python3 capture46.py [--runtime DIR] [--php BIN]
Defaults: runtime ~/scratch/fossbilling/runtime, php ~/scratch/bin/php.
"""

import argparse
import json
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
OUT = os.path.join(HERE, "captures46")

SCHEMA_DUMP_PHP = r"""<?php
// Generated by capture46.py into a temp dir at capture time (never committed).
declare(strict_types=1);
[$script, $outJson, $sqlitePath, $contentSqlPath] = $argv;
$runtimeSrc = '{RUNTIME_SRC}';
$scratchData = dirname($outJson) . '/phpdump-data';
@mkdir($scratchData, 0o755, true);
@mkdir($scratchData . '/cache', 0o755, true);
define('PATH_ROOT', $runtimeSrc);
define('PATH_LIBRARY', $runtimeSrc . '/library');
define('PATH_VENDOR', $runtimeSrc . '/vendor');
define('PATH_MODS', $runtimeSrc . '/modules');
define('PATH_DATA', $scratchData);
define('PATH_CACHE', $scratchData . '/cache');
define('DEBUG', false);
require $runtimeSrc . '/vendor/autoload.php';
use FOSSBilling\Doctrine\DriverManagerFactory;
use FOSSBilling\Doctrine\EntityManagerFactory;
use FOSSBilling\Doctrine\InstallSeeder;
use FOSSBilling\Doctrine\SchemaInstaller;
use FOSSBilling\PasswordManager;
use FOSSBilling\Version;
@unlink($sqlitePath);
$connection = DriverManagerFactory::getConnection([], ['driver' => 'pdo_sqlite', 'path' => $sqlitePath]);
$em = EntityManagerFactory::create($connection);
SchemaInstaller::createSchema($em);
$contentSql = file_get_contents($contentSqlPath);
if ($contentSql === false) {
    throw new Exception('Could not read content.sql');
}
// Fixed timestamp so the capture is deterministic; consumers compare
// shapes/counts, never this timestamp value.
$now = new DateTimeImmutable('2026-01-01 00:00:00');
InstallSeeder::seedContent($connection, $em, $contentSql, $now);
$hash = (new PasswordManager())->hashIt('Test-Admin!42');
$adminId = InstallSeeder::seedAdmin($connection, 'Test Admin', 'testadmin@example.com', $hash, null, $now);
InstallSeeder::setDefaultCurrency($connection, 'USD');
InstallSeeder::seedInstallNudge($connection, Version::VERSION, $now);
$pdo = new PDO('sqlite:' . $sqlitePath);
$tables = $pdo->query("SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY name")->fetchAll(PDO::FETCH_COLUMN);
$dump = ['tables' => [], 'total_rows' => 0, 'admin_id' => $adminId, 'admin_pass_shape' => ['prefix' => substr($hash, 0, 4), 'length' => strlen($hash)]];
foreach ($tables as $table) {
    $cols = $pdo->query("PRAGMA table_info(" . $pdo->quote($table) . ")")->fetchAll(PDO::FETCH_ASSOC);
    $columns = [];
    foreach ($cols as $c) {
        $columns[] = ['name' => $c['name'], 'type' => $c['type'], 'notnull' => (int) $c['notnull'], 'default' => $c['dflt_value'], 'pk' => (int) $c['pk']];
    }
    $indexes = [];
    foreach ($pdo->query("PRAGMA index_list(" . $pdo->quote($table) . ")")->fetchAll(PDO::FETCH_ASSOC) as $ix) {
        $ixCols = $pdo->query("PRAGMA index_info(" . $pdo->quote($ix['name']) . ")")->fetchAll(PDO::FETCH_ASSOC);
        $indexes[] = ['name' => $ix['name'], 'unique' => (int) $ix['unique'], 'origin' => $ix['origin'], 'columns' => array_column($ixCols, 'name')];
    }
    usort($indexes, static fn ($a, $b) => strcmp($a['name'], $b['name']));
    $fks = $pdo->query("PRAGMA foreign_key_list(" . $pdo->quote($table) . ")")->fetchAll(PDO::FETCH_ASSOC);
    $count = (int) $pdo->query("SELECT COUNT(*) FROM " . $pdo->quote($table))->fetchColumn();
    $dump['tables'][$table] = ['columns' => $columns, 'indexes' => $indexes, 'foreign_keys' => $fks, 'rows' => $count];
    $dump['total_rows'] += $count;
}
$dump['sqlite_sequence'] = [];
foreach ($pdo->query("SELECT name, seq FROM sqlite_sequence ORDER BY name")->fetchAll(PDO::FETCH_ASSOC) as $row) {
    $dump['sqlite_sequence'][$row['name']] = (int) $row['seq'];
}
file_put_contents($outJson, json_encode($dump, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES) . "\n");
echo 'tables=' . count($tables) . ' total_rows=' . $dump['total_rows'] . ' admin_id=' . $adminId . "\n";
"""

PLATFORM_DDL_PHP = r"""<?php
// Generated by capture46.py into a temp dir at capture time (never committed).
declare(strict_types=1);
[$script, $outJson] = $argv;
$runtimeSrc = '{RUNTIME_SRC}';
$scratchData = dirname($outJson) . '/phpddl-data';
@mkdir($scratchData, 0o755, true);
@mkdir($scratchData . '/cache', 0o755, true);
define('PATH_ROOT', $runtimeSrc);
define('PATH_LIBRARY', $runtimeSrc . '/library');
define('PATH_VENDOR', $runtimeSrc . '/vendor');
define('PATH_MODS', $runtimeSrc . '/modules');
define('PATH_DATA', $scratchData);
define('PATH_CACHE', $scratchData . '/cache');
define('DEBUG', false);
require $runtimeSrc . '/vendor/autoload.php';
use Doctrine\DBAL\Platforms\PostgreSQLPlatform;
use Doctrine\DBAL\Platforms\SQLitePlatform;
use FOSSBilling\Doctrine\DriverManagerFactory;
use FOSSBilling\Doctrine\EntityManagerFactory;
use FOSSBilling\Doctrine\ModuleEntityScope;
// Exactly SchemaInstaller::createSchema's filter.
$connection = DriverManagerFactory::getConnection([], ['driver' => 'pdo_sqlite', 'path' => $scratchData . '/meta.sqlite']);
$em = EntityManagerFactory::create($connection);
$allMetadata = $em->getMetadataFactory()->getAllMetadata();
$filtered = [];
foreach ($allMetadata as $metadata) {
    $module = ModuleEntityScope::moduleForEntityClass($metadata->getName());
    if ($module === null || ModuleEntityScope::isEagerAtInstall($module)) {
        $filtered[] = $metadata;
    }
}
$tool = new \Doctrine\ORM\Tools\SchemaTool($em);
$schema = $tool->getSchemaFromMetadata($filtered);
$out = ['metadata_total' => count($allMetadata), 'metadata_filtered' => count($filtered), 'tables' => [], 'postgres_sequences' => [], 'sqlite_sequences' => []];
$sqlitePlatform = new SQLitePlatform();
$pgPlatform = new PostgreSQLPlatform();
foreach ($schema->getTables() as $table) {
    $out['tables'][$table->getName()] = ['sqlite_ddl' => $sqlitePlatform->getCreateTableSQL($table), 'postgres_ddl' => $pgPlatform->getCreateTableSQL($table)];
}
foreach ($schema->getSequences() as $seq) {
    $out['postgres_sequences'][] = $pgPlatform->getCreateSequenceSQL($seq);
    $out['sqlite_sequences'][] = $sqlitePlatform->getCreateSequenceSQL($seq);
}
ksort($out['tables']);
file_put_contents($outJson, json_encode($out, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES) . "\n");
echo 'metadata=' . count($allMetadata) . ' filtered=' . count($filtered) . ' tables=' . count($out['tables']) . "\n";
"""

# getConfigOutput overrides, transcribed from src/install/install.php
# (function getConfigOutput; the installer starts from config-sample.php
# and overwrites exactly these keys). Values marked "computed" depend on
# installer inputs; the installer-test asserts them per input.
INSTALL_OVERRIDES = {
    "_source": "src/install/install.php getConfigOutput, transcribed from source (not executed)",
    "security.force_https": "computed: systemUrl starts with https://",
    "security.trusted_proxies": "computed: {enabled, proxies, headers} only when trusted-proxy enabled, else sample default {enabled: false, proxies: [], headers: x_forwarded}",
    "debug_and_monitoring.report_errors": "computed: (bool) installer diagnostics choice (error_reporting session value)",
    "debug_and_monitoring.debug": "computed: isDebug, false on a fresh install",
    "update_branch": "computed: 'preview' if isPreviewVersion else 'release'; 0.0.1 is preview, so fresh installs get 'preview'",
    "info.instance_id": "computed: fresh UUID v4 (Uuid::v4), never edited afterwards",
    "info.salt": "computed: bin2hex(random_bytes(16)) evaluated at require time, i.e. fresh 32 lowercase hex chars per getConfigOutput call; TS equivalent crypto.randomBytes(16).toString('hex')",
    "url": "computed: systemUrl with scheme stripped, trailing slash (normalizeSystemUrl: lowercase scheme+host, optional port, '/' + trimmed path)",
    "path_data": "computed: PATH_DATA of the install root",
    "db": "computed: sqlite {driver: pdo_sqlite, path} or {driver, host, port normalized (pgsql 5432 / mysql 3306), name, user, password}",
    "twig.cache": "computed: PATH_CACHE of the install root",
    "disable_auto_cron": "computed: !preview && !dev; false on a fresh preview install",
    "_dropped_by_r5j_scope": [
        ".htaccess fetch from GitHub (install.php throws on failure; Next routing does not use .htaccess, so a fetch failure must not fail an install)",
        "client theme config template copy (no theme files in Next)",
    ],
    "_not_in_install_portable": [
        "generateEmailTemplates (install.php post-step): syncs file-backed email templates for ACTIVE modules into email_template rows; out of R5j scope — the TS email service falls back to emailDefaults when no DB row exists, and activation syncs rows in both stacks",
        "install.php deletion after install (web-endpoint hygiene; a standalone script has nothing to delete)",
    ],
}


def run(cmd, env=None):
    r = subprocess.run(cmd, capture_output=True, text=True, env=env)
    if r.returncode != 0:
        print(r.stdout)
        print(r.stderr, file=sys.stderr)
        raise SystemExit(f"command failed ({r.returncode}): {' '.join(cmd)}")
    return r.stdout


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runtime", default=os.path.expanduser("~/scratch/fossbilling/runtime"))
    ap.add_argument("--php", default=os.path.expanduser("~/scratch/bin/php"))
    args = ap.parse_args()
    runtime_src = os.path.join(args.runtime, "src")
    content_sql = os.path.join(REPO, "src", "install", "sql", "content.sql")
    sample = os.path.join(REPO, "src", "config-sample.php")
    ref_final = os.path.join(runtime_src, "data", "update-finalization.json")
    for p in (runtime_src, content_sql, sample):
        if not os.path.exists(p):
            raise SystemExit(f"missing input: {p}")
    os.makedirs(OUT, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="capture46-") as td:
        schema_php = os.path.join(td, "schema-dump.php")
        with open(schema_php, "w") as f:
            f.write(SCHEMA_DUMP_PHP.replace("{RUNTIME_SRC}", runtime_src))
        out_schema = os.path.join(OUT, "php-fresh-schema.json")
        tmp_sqlite = os.path.join(td, "fresh.sqlite")
        print(run([args.php, schema_php, out_schema, tmp_sqlite, content_sql]).strip())
        ddl_php = os.path.join(td, "platform-ddl.php")
        with open(ddl_php, "w") as f:
            f.write(PLATFORM_DDL_PHP.replace("{RUNTIME_SRC}", runtime_src))
        out_ddl = os.path.join(OUT, "php-platform-ddl.json")
        print(run([args.php, ddl_php, out_ddl]).strip())
    # Evaluate config-sample.php (salt redacted to shape; paths are
    # location-dependent and recorded as such).
    clean_env = {k: v for k, v in os.environ.items()
                 if k not in ("DB_HOST", "DB_NAME", "DB_PORT", "DB_USER", "DB_PASSWORD")}
    php_code = (
        "$c = require $argv[1];"
        "$c['info']['salt'] = '<redacted: 32 lowercase hex chars, fresh per require>';"
        "echo json_encode($c, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES);"
    )
    sample_json = run([args.php, "-r", php_code, sample], env=clean_env)
    with open(os.path.join(OUT, "php-config-sample.json"), "w") as f:
        f.write(sample_json + "\n")
    with open(os.path.join(OUT, "php-install-overrides.json"), "w") as f:
        f.write(json.dumps(INSTALL_OVERRIDES, indent=2) + "\n")
    if os.path.exists(ref_final):
        with open(ref_final) as f:
            ref_state = json.load(f)
        with open(os.path.join(OUT, "php-finalization-reference.json"), "w") as f:
            f.write(json.dumps(ref_state, indent=2) + "\n")
        print("reference finalization state:", ref_state.get("status"), ref_state.get("version"))
    else:
        print("WARNING: reference finalization state file missing; not captured")
    # Gate: the capture must prove 86 rows / 63 tables, not bless drift.
    with open(os.path.join(OUT, "php-fresh-schema.json")) as f:
        schema = json.load(f)
    assert schema["total_rows"] == 86, f"fresh-state drift: {schema['total_rows']} != 86"
    assert len(schema["tables"]) == 63, f"table-count drift: {len(schema['tables'])} != 63"
    with open(os.path.join(OUT, "php-platform-ddl.json")) as f:
        ddl = json.load(f)
    assert len(ddl["tables"]) == 63
    assert ddl["metadata_total"] == 66 and ddl["metadata_filtered"] == 63
    print(f"OK: {len(schema['tables'])} tables, {schema['total_rows']} rows, "
          f"{ddl['metadata_total']} metadata -> {ddl['metadata_filtered']} filtered")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
